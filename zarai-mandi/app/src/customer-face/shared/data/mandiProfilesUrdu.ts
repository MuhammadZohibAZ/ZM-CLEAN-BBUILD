/** Normalize mandi name for dictionary lookup */
function normKey(s: string): string {
  return s
    .toLowerCase()
    .replace(/\s*mandi\s*/gi, "")
    .replace(/[^a-z0-9]/g, "");
}

/**
 * Returns authentic Wikipedia / agricultural profile for a mandi.
 * In Urdu mode, returns carefully written Urdu profile.
 * Falls back to dynamic localized generation if not found in dictionary.
 */
export function getMandiWikiProfile(
  rawName: string,
  isUrdu: boolean,
  meta?: {
    district?: string;
    province?: string;
    commodities?: string[];
    agriProfile?: string;
  },
  tm?: (s: string) => string,
): string {
  const stripped = stripMandi(rawName).trim();
  const key = normKey(rawName);

  if (isUrdu) {
    if (MANDI_PROFILES_URDU[key]) {
      return MANDI_PROFILES_URDU[key];
    }
    // Check partial key matches
    for (const [k, urText] of Object.entries(MANDI_PROFILES_URDU)) {
      if (key.includes(k) || k.includes(key)) {
        return urText;
      }
    }

    // Dynamic authentic Urdu generation
    const urName = tm ? tm(stripped) : stripped;
    const urDistrict = meta?.district
      ? (tm ? tm(meta.district) : meta.district).replace(/ضلع/g, "").trim()
      : "";
    const urProvince = meta?.province ? (tm ? tm(meta.province) : meta.province) : "پاکستان";
    const locPart = urDistrict ? `ضلع ${urDistrict} (${urProvince})` : urProvince;

    const commPart =
      meta?.commodities && meta.commodities.length > 0
        ? meta.commodities
            .map((c) => {
              const tr = tm ? tm(c) : c;
              if (tr && tr !== c) return tr;
              const cl = c.toLowerCase();
              if (cl.includes("wheat")) return "گندم";
              if (cl.includes("maize")) return "مکئی";
              if (cl.includes("rice")) return "چاول";
              if (cl.includes("cotton")) return "کپاس";
              if (cl.includes("sugarcane")) return "گنا";
              if (cl.includes("livestock")) return "مال مویشی";
              if (cl.includes("fruits")) return "پھل";
              if (cl.includes("vegetables")) return "سبزیاں";
              return c;
            })
            .join("، ")
        : "گندم اور دیگر علاقائی اجناس";

    return `${urName} منڈی ${locPart} کے زرعی خطے کا ایک اہم تجارتی مرکز ہے، جہاں روزانہ ${commPart} کی باقاعدہ نیلامی، بولی اور شفاف خرید و فروخت ہوتی ہے۔`;
  }

  // English mode
  if (meta?.agriProfile) {
    return meta.agriProfile;
  }

  const prov = meta?.province || "Pakistan";
  const dist = meta?.district ? `${meta.district} District, ` : "";
  return `${stripped} is an active agricultural grain market hub in ${dist}${prov}, connecting regional growers with wholesale buyers for daily transparent auctions.`;
}
